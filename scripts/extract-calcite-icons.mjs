// Copies the handful of Calcite (Esri) glyphs the Skills section uses into a small
// local module. Calcite's package blocks deep imports of its icon files, and bundling
// the whole icon set for ~20 glyphs would be wasteful.
//
// Run: node scripts/extract-calcite-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const DIR = 'node_modules/@esri/calcite-components/dist/cdn/assets/icon';
const ICONS = [
  'arcgisOnline', 'arcgisSurvey123', 'arcgisQuickcapture', 'arcgisLivingAtlas',
  'arcgisDataStore', 'dashboard', 'storymapExperience', 'urbanModel', 'portal',
  'i3DBuilding', 'i3DGlasses', 'model', 'layers', 'layerService', 'mapPin', 'map',
  'apps', 'globe', 'analysis', 'deepLearningProject', 'code', 'web',
];

const lines = ICONS.map((name) => {
  const raw = readFileSync(`${DIR}/${name}24.json`, 'utf8');
  const path = JSON.parse(raw);
  const data = typeof path === 'string' ? path : Object.values(path)[0];
  return `  ${name}: ${JSON.stringify(data)},`;
});

writeFileSync(
  'src/features/skills/esriGlyphs.js',
  `// GENERATED by scripts/extract-calcite-icons.mjs — Esri Calcite UI icons (24×24 paths).\n` +
    `// Do not edit by hand; re-run the script to add glyphs.\nexport const ESRI_GLYPHS = {\n${lines.join('\n')}\n};\n`,
);
console.log(`wrote ${ICONS.length} glyphs`);
